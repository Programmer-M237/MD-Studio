#!/usr/bin/env python3
"""
Generates src/MathGlyphData.h from the OpenType MATH table of Latin Modern Math.

The Qt API cannot read the MATH table, so we extract the pieces the renderer needs:
  * size variants + glyph assemblies for stretchy characters (delimiters, radical,
    big operators, wide accents, over/under braces)
  * italic corrections and top-accent attachment points per glyph

Usage:  python3 tools/gen_math_glyphs.py resources/fonts/latinmodern-math.otf > src/MathGlyphData.h
Requires: pip install fonttools
"""
import sys
from fontTools.ttLib import TTFont

font = TTFont(sys.argv[1])
order = font.getGlyphOrder()
gid = font.getGlyphID
cmap = font.getBestCmap()
rev = {}
for cp, name in cmap.items():
    rev.setdefault(name, cp)
math = font['MATH'].table
var = math.MathVariants

def constructions(coverage, records):
    out = []
    for name, rec in zip(coverage.glyphs, records):
        cp = rev.get(name)
        if cp is None:
            continue
        variants = [(gid(v.VariantGlyph), v.AdvanceMeasurement) for v in (rec.MathGlyphVariantRecord or [])]
        parts = []
        if rec.GlyphAssembly:
            for p in rec.GlyphAssembly.PartRecords:
                parts.append((gid(p.glyph), p.StartConnectorLength, p.EndConnectorLength,
                              p.FullAdvance, 1 if (p.PartFlags & 1) else 0))
        if variants or parts:
            out.append((cp, gid(name), variants, parts))
    return sorted(out)

vert = constructions(var.VertGlyphCoverage, var.VertGlyphConstruction) if var.VertGlyphCoverage else []
horiz = constructions(var.HorizGlyphCoverage, var.HorizGlyphConstruction) if var.HorizGlyphCoverage else []

def glyph_value_table(info_attr, cov_attr, val_attr):
    info = getattr(math.MathGlyphInfo, info_attr)
    if info is None:
        return []
    cov = getattr(info, cov_attr)
    vals = getattr(info, val_attr)
    return sorted((gid(n), v.Value) for n, v in zip(cov.glyphs, vals))

italic = glyph_value_table('MathItalicsCorrectionInfo', 'Coverage', 'ItalicsCorrection')
topacc = glyph_value_table('MathTopAccentAttachment', 'TopAccentCoverage', 'TopAccentAttachment')

def emit(kind, items):
    print(f"// ---- {kind} constructions ----")
    vv, pp, rows = [], [], []
    for cp, base, variants, parts in items:
        rows.append((cp, base, len(vv), len(variants), len(pp), len(parts)))
        vv += variants
        pp += parts
    print(f"static const MGVariant k{kind}Variants[] = {{")
    print(",".join(f"{{{g},{s}}}" for g, s in vv) or "{0,0}")
    print("};")
    print(f"static const MGPart k{kind}Parts[] = {{")
    print(",".join(f"{{{g},{a},{b},{c},{d}}}" for g, a, b, c, d in pp) or "{0,0,0,0,0}")
    print("};")
    print(f"static const MGConstruction k{kind}Constructions[] = {{")
    print(",\n".join(f"{{0x{cp:X},{base},{vo},{vn},{po},{pn}}}" for cp, base, vo, vn, po, pn in rows) or "{0,0,0,0,0,0}")
    print("};")
    print(f"static const int k{kind}ConstructionCount = {len(rows)};")

print("// GENERATED by tools/gen_math_glyphs.py from Latin Modern Math - do not edit.")
print("#pragma once")
print("#include <cstdint>")
print("struct MGVariant      { uint16_t glyph; uint16_t size; };")
print("struct MGPart         { uint16_t glyph, startConn, endConn, fullAdvance, extender; };")
print("struct MGConstruction { uint32_t cp; uint16_t baseGlyph; uint16_t varOff, varCount, partOff, partCount; };")
print("struct MGValue        { uint16_t glyph; int16_t value; };")
print(f"static const int kMinConnectorOverlap = {var.MinConnectorOverlap};")
emit("Vert", vert)
emit("Horiz", horiz)
print("static const MGValue kItalicCorrection[] = {")
print(",".join(f"{{{g},{v}}}" for g, v in italic))
print("};")
print(f"static const int kItalicCorrectionCount = {len(italic)};")
print("static const MGValue kTopAccent[] = {")
print(",".join(f"{{{g},{v}}}" for g, v in topacc))
print("};")
print(f"static const int kTopAccentCount = {len(topacc)};")
